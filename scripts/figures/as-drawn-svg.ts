#!/usr/bin/env bun
/**
 * Draw each `as-drawn-figure/v1` data file in figure-data/as-drawn/ as an SVG
 * in folio/dth-sc/media/as-drawn-<fig>.svg: the same paths, colours and text
 * at the same places as the source PDF draws them. Labels are SVG <text>
 * (searchable, translatable), held to their printed width; a label that names
 * a glossary term links to it.
 *
 *   bun run scripts/figures/as-drawn-svg.ts           # write the SVGs
 *   bun run scripts/figures/as-drawn-svg.ts --check   # fail when data is invalid or an SVG is stale
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { AsDrawnFigureSchema, type AsDrawnFigure } from "./as-drawn-figure.ts";

const DATA = "figure-data/as-drawn";
const MEDIA = "folio/dth-sc/media";
const FONT = "'Source Sans Pro','Source Sans 3','Helvetica Neue',Arial,sans-serif";

const clipped = (el: string, clip?: number[]) => {
  for (const c of [...(clip ?? [])].reverse()) el = `<g clip-path="url(#c${c})">${el}</g>`;
  return el;
};

const esc = (s: string) =>
  s.replace(/&/gu, "&amp;").replace(/</gu, "&lt;").replace(/>/gu, "&gt;").replace(/"/gu, "&quot;");

export function renderAsDrawn(fig: AsDrawnFigure): string {
  const { width, height } = fig.canvas;
  const title = fig.figure.caption ?? fig.figure.labels.join(", ");
  const out: string[] = [];
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}" role="img" aria-labelledby="t">`);
  out.push(`<title id="t">${esc(title)}</title>`);
  out.push(`<desc>Redrawn as drawn from WHO, Digital transformation handbook for health supply chain architecture (2024), PDF page ${fig.figure.page}: generated by scripts/figures/as-drawn-svg.ts from figure-data/as-drawn data (${esc(fig.figure.render)}).</desc>`);
  if (fig.clips.length) {
    out.push(`<defs>`);
    fig.clips.forEach((c, i) =>
      out.push(`<clipPath id="c${i}" clipPathUnits="userSpaceOnUse"><path d="${c.d}"${c.evenodd ? ` clip-rule="evenodd"` : ""}/></clipPath>`));
    out.push(`</defs>`);
  }
  out.push(`<g fill="none" stroke-linecap="butt" stroke-linejoin="miter">`);
  for (const s of fig.shapes) {
    const a = [`d="${s.d}"`];
    a.push(`fill="${s.fill ?? "none"}"`);
    if (s.evenodd) a.push(`fill-rule="evenodd"`);
    if (s.stroke) {
      a.push(`stroke="${s.stroke}"`, `stroke-width="${s.strokeWidth ?? 1}"`);
      if (s.dash?.length) a.push(`stroke-dasharray="${s.dash.join(" ")}"`);
      if (s.cap) a.push(`stroke-linecap="${s.cap}"`);
      if (s.join) a.push(`stroke-linejoin="${s.join}"`);
      if (s.strokeOpacity !== undefined) a.push(`stroke-opacity="${s.strokeOpacity}"`);
    }
    if (s.fillOpacity !== undefined) a.push(`fill-opacity="${s.fillOpacity}"`);
    out.push(clipped(`<path ${a.join(" ")}/>`, s.clip));
  }
  out.push(`</g>`);
  for (const im of fig.images ?? []) {
    out.push(clipped(`<image x="${im.x}" y="${im.y}" width="${im.width}" height="${im.height}" preserveAspectRatio="none" href="data:image/png;base64,${im.png}"/>`, im.clip));
  }
  out.push(`<g font-family="${FONT}" fill="#000000">`);
  for (const t of fig.texts) {
    const a = [`x="${t.x}"`, `y="${t.y}"`, `font-size="${t.size}"`];
    if (t.weight) a.push(`font-weight="${t.weight}"`);
    if (t.italic) a.push(`font-style="italic"`);
    if (t.color) a.push(`fill="${t.color}"`);
    if (t.width) a.push(`textLength="${t.width}"`, `lengthAdjust="spacingAndGlyphs"`);
    if (t.rotate) a.push(`transform="rotate(${t.rotate} ${t.x} ${t.y})"`);
    const el = `<text ${a.join(" ")}>${esc(t.text)}</text>`;
    out.push(clipped(t.link ? `<a href="${esc(t.link)}"><title>${esc(t.link)}</title>${el}</a>` : el, t.clip));
  }
  out.push(`</g>`, `</svg>`);
  return out.join("\n") + "\n";
}

export const svgName = (fig: AsDrawnFigure) =>
  `as-drawn-fig-${fig.figure.labels.map((l) => l.replace("Fig. ", "")).join("-")}.svg`;

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let bad = 0;
  const files = readdirSync(DATA).filter((f) => f.endsWith(".json")).sort();
  for (const f of files) {
    const parsed = AsDrawnFigureSchema.safeParse(JSON.parse(readFileSync(`${DATA}/${f}`, "utf-8")));
    if (!parsed.success) {
      console.error(`✗ ${DATA}/${f}: ${parsed.error.issues.slice(0, 3).map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
      bad++;
      continue;
    }
    const out = `${MEDIA}/${svgName(parsed.data)}`;
    const svg = renderAsDrawn(parsed.data);
    if (check) {
      if (!existsSync(out) || readFileSync(out, "utf-8") !== svg) {
        console.error(`✗ ${out} is out of date: run scripts/figures/as-drawn-svg.ts`);
        bad++;
      }
    } else {
      writeFileSync(out, svg);
      console.log(`wrote ${out}`);
    }
  }
  if (check) console.log(bad ? `✗ ${bad} as-drawn figure(s) invalid or stale` : `✓ ${files.length} as-drawn SVGs match their data`);
  process.exit(bad ? 1 : 0);
}
